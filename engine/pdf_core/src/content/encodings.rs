/// Encodage de base d'une police simple.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum BaseEncoding {
    /// StandardEncoding (par défaut des polices Type 1 non symboliques).
    Standard,
    /// WinAnsiEncoding.
    WinAnsi,
    /// MacRomanEncoding.
    MacRoman,
}

impl BaseEncoding {
    /// Encodage désigné par son nom PDF.
    pub fn from_name(name: &[u8]) -> Option<Self> {
        match name {
            b"WinAnsiEncoding" => Some(Self::WinAnsi),
            b"MacRomanEncoding" | b"MacExpertEncoding" => Some(Self::MacRoman),
            b"StandardEncoding" | b"PDFDocEncoding" => Some(Self::Standard),
            _ => None,
        }
    }

    /// Caractère du code `code`, s'il est défini.
    pub fn char(self, code: u8) -> Option<char> {
        let table = match self {
            Self::Standard => &STANDARD,
            Self::WinAnsi => &WIN_ANSI,
            Self::MacRoman => &MAC_ROMAN,
        };
        match table[code as usize] {
            0 => None,
            value => char::from_u32(u32::from(value)),
        }
    }
}

/// Texte d'un nom de glyphe : « eacute » → « é », « f_i » → « fi »,
/// « uni00E9 » → « é », « a.sc » → « a ». `None` si le nom est inconnu.
pub fn glyph_name_text(name: &str) -> Option<String> {
    // Un suffixe après le point (variante stylistique) est ignoré.
    let name = name.split('.').next().unwrap_or(name);
    if name.is_empty() {
        return None;
    }
    if name.contains('_') {
        let parts: Option<Vec<String>> = name.split('_').map(glyph_name_text).collect();
        return parts.map(|parts| parts.concat());
    }
    if let Ok(index) =
        GLYPH_NAMES.binary_search_by(|(known, _)| known.as_bytes().cmp(name.as_bytes()))
    {
        return Some(GLYPH_NAMES[index].1.to_string());
    }
    if let Some(hex) = name.strip_prefix("uni") {
        if hex.len() >= 4 && hex.len() % 4 == 0 && hex.bytes().all(|b| b.is_ascii_hexdigit()) {
            let units: Vec<u16> = (0..hex.len() / 4)
                .filter_map(|i| u16::from_str_radix(&hex[i * 4..i * 4 + 4], 16).ok())
                .collect();
            let text: String = char::decode_utf16(units).filter_map(Result::ok).collect();
            return (!text.is_empty()).then_some(text);
        }
    }
    if let Some(hex) = name.strip_prefix('u') {
        if (4..=6).contains(&hex.len()) && hex.bytes().all(|b| b.is_ascii_hexdigit()) {
            return u32::from_str_radix(hex, 16)
                .ok()
                .and_then(char::from_u32)
                .map(String::from);
        }
    }
    None
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn la_table_des_noms_est_triee() {
        assert!(GLYPH_NAMES
            .windows(2)
            .all(|pair| pair[0].0.as_bytes() < pair[1].0.as_bytes()));
    }

    #[test]
    fn noms_de_glyphes() {
        assert_eq!(glyph_name_text("eacute").as_deref(), Some("é"));
        assert_eq!(glyph_name_text("Euro").as_deref(), Some("€"));
        assert_eq!(glyph_name_text("f_i").as_deref(), Some("fi"));
        assert_eq!(glyph_name_text("uni00E9").as_deref(), Some("é"));
        assert_eq!(glyph_name_text("u1F600").as_deref(), Some("😀"));
        assert_eq!(glyph_name_text("a.sc").as_deref(), Some("a"));
        assert_eq!(glyph_name_text("oe").as_deref(), Some("œ"));
        assert_eq!(glyph_name_text("g123"), None);
    }

    #[test]
    fn encodages_de_base() {
        assert_eq!(BaseEncoding::WinAnsi.char(0x80), Some('€'));
        assert_eq!(BaseEncoding::WinAnsi.char(0xE9), Some('é'));
        assert_eq!(BaseEncoding::WinAnsi.char(0x9C), Some('œ'));
        assert_eq!(BaseEncoding::MacRoman.char(0x8E), Some('é'));
        assert_eq!(BaseEncoding::Standard.char(0x27), Some('’'));
        assert_eq!(BaseEncoding::Standard.char(0xAE), Some('ﬁ'));
        assert_eq!(BaseEncoding::Standard.char(0x80), None);
    }
}
